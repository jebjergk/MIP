-- 10. Verification queries
------------------------------------------------------------------------
SELECT 'LIVE_ACTIONS structural columns' AS CHECK_NAME,
       COUNT(*) AS COL_COUNT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'LIVE'
  AND TABLE_NAME = 'LIVE_ACTIONS'
  AND COLUMN_NAME IN (
      'SETUP_EVENT_ID', 'MARKET_TYPE', 'SETUP_FAMILY', 'DIRECTION',
      'ENTRY_ZONE_LOW', 'ENTRY_ZONE_HIGH', 'SUPPORTING_LEVEL',
      'INVALIDATION_LEVEL', 'INVALIDATION_RULE', 'STRUCTURE_CONFIDENCE',
      'LEVEL_SIGNIFICANCE', 'STRUCTURAL_STATE', 'REGIME_TAGS', 'REGIME_COMPAT',
      'TRUST_LABEL', 'MEANINGFUL_HIT_RATE', 'PATH_SURVIVAL_RATE',
      'MFE_MAE_RATIO', 'AVG_BARS_TO_THRESHOLD', 'DOMINANT_FAILURE_MODE', 'BEST_WINDOW',
      'RISK_CLASS', 'EXIT_STYLE', 'TRAIL_STYLE', 'TRAIL_PARAMS',
      'TRAIL_ACTIVATION_TYPE', 'TRAIL_ACTIVATION_PARAM',
      'EXPECTED_HOLD_CHARACTER', 'MAX_HOLD_BARS',
      'SETUP_NARRATIVE', 'PROPOSAL_RATIONALE',
      'LATEST_BAR_DATE', 'CURRENT_PRICE', 'DISTANCE_TO_ENTRY_ZONE',
      'SETUP_STILL_VALID', 'PRICE_MOVED_TOO_FAR', 'FRESHNESS_ASSESSMENT'
  );

SELECT 'LIVE_ORDERS protection/trail columns' AS CHECK_NAME,
       COUNT(*) AS COL_COUNT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'LIVE'
  AND TABLE_NAME = 'LIVE_ORDERS'
  AND COLUMN_NAME IN (
      'PARENT_ORDER_ID', 'ORDER_ROLE', 'PROTECTION_TYPE', 'OCA_GROUP', 'STOP_PRICE',
      'TRAIL_STYLE', 'TRAIL_ACTIVATION_TYPE', 'TRAIL_ACTIVATION_PARAM',
      'TRAIL_AMOUNT', 'TRAIL_PERCENT', 'TRAIL_ACTIVATION_PRICE',
      'TRAIL_ACTIVATED', 'TRAIL_ACTIVATED_AT', 'LAST_KNOWN_STOP_LEVEL', 'BROKER_TRAIL_STATE'
  );

SELECT 'APP_CONFIG trailing flags' AS CHECK_NAME,
       COUNT(*) AS FLAG_COUNT
FROM MIP.APP.APP_CONFIG
WHERE CONFIG_KEY IN ('TRAIL_ENABLED', 'TRAIL_SHORT_ENABLED', 'TRAIL_STYLES_ALLOWED', 'TRAIL_DRY_RUN', 'LIVE_ENFORCE_LONG_ONLY');
