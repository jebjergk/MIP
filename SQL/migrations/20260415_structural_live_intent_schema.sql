-- 9. APP_CONFIG — Trailing stop feature flags + long-only enforcement
------------------------------------------------------------------------
MERGE INTO MIP.APP.APP_CONFIG t
USING (
    SELECT 'TRAIL_ENABLED' AS CONFIG_KEY,
           'false'         AS CONFIG_VALUE,
           'Master switch for trailing stop order creation. Must be TRUE before any trailing orders are placed.' AS DESCRIPTION
    UNION ALL
    SELECT 'TRAIL_SHORT_ENABLED',
           'false',
           'Allow trailing stops on SHORT positions. Requires TRAIL_ENABLED=true. Gated behind short-side verification.'
    UNION ALL
    SELECT 'TRAIL_STYLES_ALLOWED',
           'STRUCTURAL',
           'Comma-separated list of allowed trail styles: STRUCTURAL, PROGRESS_BASED, HYBRID.'
    UNION ALL
    SELECT 'TRAIL_DRY_RUN',
           'true',
           'When true, trailing stop decisions are logged but no orders are placed at broker.'
    UNION ALL
    SELECT 'LIVE_ENFORCE_LONG_ONLY',
           'true',
           'When true, the live chain blocks SHORT entries. Set to false after short-side protection is verified.'
) s
ON t.CONFIG_KEY = s.CONFIG_KEY
WHEN NOT MATCHED THEN INSERT (CONFIG_KEY, CONFIG_VALUE, DESCRIPTION, UPDATED_AT)
VALUES (s.CONFIG_KEY, s.CONFIG_VALUE, s.DESCRIPTION, CURRENT_TIMESTAMP());

