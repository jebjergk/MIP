/* Phase 9A — durable experiment orchestration (historical data / simulation only) */
USE DATABASE MIP;
USE SCHEMA APP;

CREATE TABLE IF NOT EXISTS MIP.APP.BROOKS_EXPERIMENT_EXECUTION (
    EXECUTION_ID           VARCHAR(36)   NOT NULL PRIMARY KEY,
    FREEZE_ID              VARCHAR(64)   NOT NULL,
    COHORT_JSON            VARIANT       NOT NULL,
    OVERALL_STATUS         VARCHAR(32)   NOT NULL,
    CURRENT_WEEK_START     DATE,
    VALIDATION_RUN_ID      VARCHAR(36),
    CURRENT_STAGE          VARCHAR(48),
    REQUESTED_ACTION       VARCHAR(32),
    PAUSE_REQUESTED        BOOLEAN       DEFAULT FALSE,
    RUN_ALL_REMAINING      BOOLEAN       DEFAULT FALSE,
    PROGRESS_JSON          VARIANT,
    ATTEMPT_IDS_JSON       VARIANT,
    TWS_STATE_JSON         VARIANT,
    LATEST_ERROR_JSON      VARIANT,
    LAST_SUCCESS_ACTION    VARCHAR(512),
    NEXT_AUTOMATIC_ACTION  VARCHAR(512),
    LEASE_OWNER            VARCHAR(128),
    LEASE_UNTIL            TIMESTAMP_NTZ,
    HEARTBEAT_AT           TIMESTAMP_NTZ,
    CREATED_AT             TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT             TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS MIP.APP.BROOKS_EXPERIMENT_STAGE (
    EXECUTION_ID           VARCHAR(36)   NOT NULL,
    WEEK_START             DATE          NOT NULL,
    STAGE_KEY              VARCHAR(48)   NOT NULL,
    STAGE_STATUS           VARCHAR(32)   NOT NULL,
    STARTED_AT             TIMESTAMP_NTZ,
    FINISHED_AT            TIMESTAMP_NTZ,
    ATTEMPT_ID             VARCHAR(36),
    ROW_COUNT              NUMBER,
    CONTENT_HASH           VARCHAR(128),
    RETRY_COUNT            NUMBER        DEFAULT 0,
    ERROR_JSON             VARIANT,
    UPDATED_AT             TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (EXECUTION_ID, WEEK_START, STAGE_KEY)
);

CREATE TABLE IF NOT EXISTS MIP.APP.BROOKS_EXPERIMENT_EVENT (
    EVENT_ID               NUMBER AUTOINCREMENT PRIMARY KEY,
    EXECUTION_ID           VARCHAR(36)   NOT NULL,
    EVENT_TS               TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    SEVERITY               VARCHAR(16)   NOT NULL,
    STAGE                  VARCHAR(48),
    WEEK_START             DATE,
    SYMBOL                 VARCHAR(20),
    TRADING_DATE           DATE,
    MESSAGE                VARCHAR(2000) NOT NULL,
    DETAIL_JSON            VARIANT,
    RECOVERABLE            BOOLEAN
);

COMMENT ON TABLE MIP.APP.BROOKS_EXPERIMENT_EXECUTION IS 'Phase 9 unseen-week validation orchestration. No live IB orders.';

USE ROLE MIP_ADMIN_ROLE;
GRANT SELECT, INSERT, UPDATE ON TABLE MIP.APP.BROOKS_EXPERIMENT_EXECUTION TO ROLE MIP_UI_API_ROLE;
GRANT SELECT, INSERT, UPDATE ON TABLE MIP.APP.BROOKS_EXPERIMENT_STAGE TO ROLE MIP_UI_API_ROLE;
GRANT SELECT, INSERT ON TABLE MIP.APP.BROOKS_EXPERIMENT_EVENT TO ROLE MIP_UI_API_ROLE;
